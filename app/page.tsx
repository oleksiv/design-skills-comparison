function Check({ on }: { on: boolean }) {
  return on ? (
    <span className="inline-flex size-6 items-center justify-center rounded-full bg-emerald-100 text-emerald-700">
      <svg viewBox="0 0 16 16" className="size-3.5" fill="none" stroke="currentColor" strokeWidth="2.5" strokeLinecap="round" strokeLinejoin="round" aria-hidden="true">
        <path d="M3 8.5l3.2 3.2L13 4.8" />
      </svg>
      <span className="sr-only">Yes</span>
    </span>
  ) : (
    <span className="inline-flex size-6 items-center justify-center rounded-full bg-red-50 text-red-500">
      <svg viewBox="0 0 16 16" className="size-3" fill="none" stroke="currentColor" strokeWidth="2.5" strokeLinecap="round" aria-hidden="true">
        <path d="M4 4l8 8M12 4l-8 8" />
      </svg>
      <span className="sr-only">No</span>
    </span>
  );
}

function Stars({ n }: { n: number }) {
  return (
    <span className="whitespace-nowrap text-lg leading-none" role="img" aria-label={`${n} of 3`}>
      {[1, 2, 3].map((i) => (
        <span key={i} className={i <= n ? "text-amber-400" : "text-zinc-200"}>
          ★
        </span>
      ))}
    </span>
  );
}

